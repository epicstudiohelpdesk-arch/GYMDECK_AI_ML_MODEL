@MainActor
private final class PreviewHarness {
    let defaults: UserDefaults
    let suite = "VoicePreviewTests.\(UUID().uuidString)"
    var settings: VoiceAssistantSettings { VoiceAssistantSettings(defaults: defaults) }
    let audio = PreviewAudio()
    let notifications = NotificationCenter()
    var sessions: [PreviewSession] = []
    var busy = false
    var route: VoiceAssistantRoute
    var preview: VoicePreviewController!

    init(
        provider: LiveProvider = .gemini,
        credential: @escaping @MainActor (LiveProvider) async -> LiveSessionConfig.Credential? = {
            $0 == .hosted ? .hostedUser("test-user") : .apiKey("test-key")
        },
        waitForDeadline: @escaping @Sendable () async throws -> Void = { try await Task.sleep(for: .seconds(30)) },
        quietFinishDelay: Duration = .milliseconds(100)
    ) {
        defaults = UserDefaults(suiteName: suite)!
        route = .ready(provider)
        preview = VoicePreviewController(
            settings: settings, resolveRoute: { [unowned self] in self.route },
            assistantIsBusy: { [unowned self] in self.busy }, credential: credential,
            makeSession: { [unowned self] config, callback in
                let session = PreviewSession(config: config, callback: callback)
                self.sessions.append(session)
                return session
            }, makeAudio: { [unowned self] in self.audio }, notificationCenter: notifications,
            waitForDeadline: waitForDeadline, quietFinishDelay: quietFinishDelay
        )
    }

    func startReady() async throws -> PreviewSession {
        let expected = sessions.count + 1
        preview.start(appLanguageCode: "en", sample: "Fixed sample")
        try await waitUntil { sessions.count == expected }
        let session = sessions[expected - 1]
        session.emit(.ready)
        try await waitUntil { session.samples.count == 1 }
        return session
    }

    func close() {
        preview.stop()
        defaults.removePersistentDomain(forName: suite)
    }
}

@MainActor
private final class PreviewSession: VoicePreviewSession {
    let config: LiveSessionConfig
    let callback: @Sendable (LiveEvent) -> Void
    var connected = false
    var closed = false
    var samples: [String] = []
    var responseRequests = 0
    init(config: LiveSessionConfig, callback: @escaping @Sendable (LiveEvent) -> Void) {
        self.config = config
        self.callback = callback
    }
    func connect() { connected = true }
    func send(contextText: String) { samples.append(contextText) }
    func requestResponse() { responseRequests += 1 }
    func close() { closed = true }
    func emit(_ event: LiveEvent) { callback(event) }
}

@MainActor
private final class PreviewAudio: LivePlaybackIO {
    var onPlaybackFinished: (() -> Void)?
    var onInterrupted: (() -> Void)?
    var isPlaying = false
    var starts: [Double] = []
    var chunks: [Data] = []
    var stopCount = 0
    var failStart = false
    func startPlayback(outputSampleRate: Double) throws {
        starts.append(outputSampleRate)
        if failStart { throw PreviewTestFailure.audioUnavailable }
    }
    func play(_ pcm16: Data) { chunks.append(pcm16); isPlaying = true }
    func stop() { stopCount += 1; isPlaying = false; onPlaybackFinished = nil; onInterrupted = nil }
    func finish() { isPlaying = false; onPlaybackFinished?() }
}

@MainActor
private final class PreviewCredentialGate {
    var waiting: CheckedContinuation<LiveSessionConfig.Credential?, Never>?
    func read() async -> LiveSessionConfig.Credential? {
        await withCheckedContinuation { waiting = $0 }
    }
    func complete() { waiting?.resume(returning: .apiKey("test-key")); waiting = nil }
}

private actor PreviewDeadlineGate {
    private var waiting: CheckedContinuation<Void, Never>?
    private var expired = false
    func wait() async {
        if expired { return }
        await withCheckedContinuation { waiting = $0 }
    }
    func expire() { expired = true; waiting?.resume(); waiting = nil }
}

@MainActor
private func waitUntil(_ condition: () -> Bool) async throws {
    for _ in 0..<200 {
        if condition() { return }
        try await Task.sleep(for: .milliseconds(10))
    }
    throw PreviewTestFailure.conditionNotReached
}

@MainActor
private func flushEvents() async {
    // Socket callbacks enqueue main-queue blocks, so a queue barrier observes all
    // earlier events without making assumptions about scheduler timing.
    await withCheckedContinuation { continuation in
        DispatchQueue.main.async { continuation.resume() }
    }
}

private enum PreviewTestFailure: Error { case conditionNotReached, audioUnavailable }
