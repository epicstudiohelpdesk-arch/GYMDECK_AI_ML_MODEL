import Foundation
import Testing
import UIKit
@testable import calorietracker

@MainActor
struct VoicePreviewTests {
    @Test(arguments: LiveProvider.allCases)
    func usesSelectedConfigurationWithoutToolsOrMicrophone(provider: LiveProvider) async throws {
        let harness = PreviewHarness(provider: provider)
        defer { harness.close() }
        let model = provider.models.last!
        let voice = provider.voices.last!
        harness.settings.setModel(model, for: provider)
        harness.settings.setVoice(voice, for: provider)
        harness.settings.language = .specific("de")
        harness.preview.start(appLanguageCode: "en", sample: "Fixed sample")
        try await waitUntil { harness.sessions.count == 1 }
        let session = harness.sessions[0]
        #expect(session.connected)
        #expect(session.config.provider == provider)
        #expect(session.config.model == model)
        #expect(session.config.voice == voice)
        #expect(session.config.credential == (provider == .hosted ? .hostedUser("test-user") : .apiKey("test-key")))
        #expect(session.config.tools.isEmpty)
        #expect(session.config.instructions.contains("German"))
        #expect(harness.audio.starts.isEmpty)
        session.emit(.ready)
        try await waitUntil { session.samples.count == 1 }
        #expect(session.samples == ["Fixed sample"])
        #expect(session.responseRequests == 1)
        #expect(harness.audio.starts == [provider.wire.outputSampleRate])
        // A reconnect/setup acknowledgement cannot replay the sample or recreate audio.
        session.emit(.ready)
        await flushEvents()
        #expect(session.samples.count == 1)
        #expect(harness.audio.starts.count == 1)
    }

    @Test func closesNetworkAtCompletionButDrainsEveryQueuedAudioChunk() async throws {
        let harness = PreviewHarness()
        defer { harness.close() }
        let session = try await harness.startReady()
        session.emit(.audio(Data([1, 2]), itemID: nil))
        try await waitUntil { harness.audio.chunks.count == 1 }
        // A temporary gap between chunks does not mean the provider is finished.
        harness.audio.finish()
        #expect(harness.preview.isRunning)
        #expect(!session.closed)
        session.emit(.audio(Data([3, 4]), itemID: nil))
        session.emit(.turnComplete)
        try await waitUntil { session.closed }
        #expect(harness.audio.chunks == [Data([1, 2]), Data([3, 4])])
        #expect(harness.preview.phase == .playing)
        #expect(harness.audio.stopCount == 0)
        // The close event generated by our own close must not cut off playback.
        session.emit(.closed(nil))
        await flushEvents()
        #expect(harness.preview.isRunning)
        harness.audio.finish()
        #expect(!harness.preview.isRunning)
        #expect(harness.preview.errorMessage == nil)
        #expect(harness.audio.stopCount == 1)
    }

    @Test func gptLiveSampleEndsWhenAudioGoesQuietNotWhenItsBackendFinishes() async throws {
        let harness = PreviewHarness(provider: .gptLive)
        defer { harness.close() }
        let session = try await harness.startReady()
        // The backend finishes before GPT-Live speaks the sample.
        session.emit(.responseDone(hasToolCalls: true))
        await flushEvents()
        #expect(harness.preview.isRunning)
        #expect(harness.preview.errorMessage == nil)
        session.emit(.audio(Data([1, 2]), itemID: nil))
        try await waitUntil { harness.audio.chunks.count == 1 }
        try await waitUntil { session.closed }
        #expect(harness.preview.isRunning)
        harness.audio.finish()
        #expect(!harness.preview.isRunning)
        #expect(harness.preview.errorMessage == nil)
    }

    @Test func gptLiveUnsuccessfulBackendCompletionFailsThePreview() async throws {
        let harness = PreviewHarness(provider: .gptLive)
        defer { harness.close() }
        let session = try await harness.startReady()
        session.emit(.responseDone(hasToolCalls: true, successful: false))
        try await waitUntil { !harness.preview.isRunning }
        #expect(harness.preview.errorMessage != nil)
    }

    @Test func completionAfterPlaybackAlreadyDrainedReturnsIdle() async throws {
        let harness = PreviewHarness(provider: .openai)
        defer { harness.close() }
        let session = try await harness.startReady()
        session.emit(.audio(Data([1, 2]), itemID: "reply"))
        try await waitUntil { harness.audio.isPlaying }
        harness.audio.finish()
        session.emit(.responseDone(hasToolCalls: false))
        try await waitUntil { !harness.preview.isRunning }
        #expect(session.closed)
        #expect(harness.preview.errorMessage == nil)
    }

    @Test(arguments: ["cancelled", "incomplete"])
    func unsuccessfulResponseStopsPartialPlaybackAndShowsFailure(status: String) async throws {
        let harness = PreviewHarness(provider: .openai)
        defer { harness.close() }
        let session = try await harness.startReady()
        session.emit(.audio(Data([1, 2]), itemID: "partial"))
        try await waitUntil { harness.audio.isPlaying }
        let wire = OpenAIRealtimeWire()
        let completion = LiveJSON.string(["type": "response.done", "response": ["id": "preview", "status": status]])
        for event in wire.parse(completion) { session.emit(event) }
        try await waitUntil { !harness.preview.isRunning }
        #expect(session.closed)
        #expect(!harness.audio.isPlaying)
        #expect(harness.audio.stopCount == 1)
        #expect(harness.preview.errorMessage == String(localized: "Couldn’t play this voice preview. Please try again."))
    }

    @Test func stopAndRestartRejectOldSocketAndPlaybackCallbacks() async throws {
        let harness = PreviewHarness()
        defer { harness.close() }
        let old = try await harness.startReady()
        let staleDrain = harness.audio.onPlaybackFinished
        let staleInterruption = harness.audio.onInterrupted
        harness.preview.stop()
        harness.preview.start(appLanguageCode: "en", sample: "New sample")
        try await waitUntil { harness.sessions.count == 2 }
        let current = harness.sessions[1]
        old.emit(.ready)
        old.emit(.audio(Data([1, 2]), itemID: nil))
        old.emit(.error("private-provider-payload", code: nil))
        staleDrain?()
        staleInterruption?()
        await flushEvents()
        #expect(harness.preview.phase == .preparing)
        #expect(harness.preview.errorMessage == nil)
        #expect(harness.audio.chunks.isEmpty)
        #expect(!current.closed)
        current.emit(.ready)
        try await waitUntil { current.samples == ["New sample"] }
    }

    @Test func cancelledCredentialLookupCannotStartAConnection() async throws {
        let gate = PreviewCredentialGate()
        let harness = PreviewHarness(credential: { _ in await gate.read() })
        defer { harness.close() }
        harness.preview.start(appLanguageCode: "en", sample: "Fixed sample")
        try await waitUntil { gate.waiting != nil }
        harness.preview.stop()
        gate.complete()
        await flushEvents()
        #expect(harness.sessions.isEmpty)
        #expect(harness.audio.starts.isEmpty)
        #expect(!harness.preview.isRunning)
    }

    @Test func assistantStartingDuringCredentialLookupPreventsPreviewAudio() async throws {
        let gate = PreviewCredentialGate()
        let harness = PreviewHarness(credential: { _ in await gate.read() })
        defer { harness.close() }
        harness.preview.start(appLanguageCode: "en", sample: "Fixed sample")
        try await waitUntil { gate.waiting != nil }
        harness.busy = true
        gate.complete()
        try await waitUntil { !harness.preview.isRunning }
        #expect(harness.sessions.isEmpty)
        #expect(harness.audio.starts.isEmpty)
    }

    @Test func missingAccessAndActiveConversationNeverConnect() async throws {
        let harness = PreviewHarness()
        defer { harness.close() }
        harness.route = .needsAccess(.missingKey(.gemini))
        harness.preview.start(appLanguageCode: "en", sample: "Fixed sample")
        #expect(!harness.preview.isRunning)
        #expect(harness.preview.errorMessage != nil)
        harness.route = .ready(.gemini)
        harness.busy = true
        harness.preview.start(appLanguageCode: "en", sample: "Fixed sample")
        #expect(!harness.preview.isRunning)
        #expect(harness.preview.errorMessage == String(localized: "End your current voice conversation before previewing a voice."))
        await flushEvents()
        #expect(harness.sessions.isEmpty)
        #expect(harness.audio.starts.isEmpty)
    }

    @Test func missingCredentialAndPlaybackStartupFailureCleanUpWithoutSendingSample() async throws {
        let missing = PreviewHarness(credential: { _ in nil })
        defer { missing.close() }
        missing.preview.start(appLanguageCode: "en", sample: "Fixed sample")
        try await waitUntil { !missing.preview.isRunning }
        #expect(missing.sessions.isEmpty)
        #expect(missing.audio.starts.isEmpty)
        #expect(missing.preview.errorMessage != nil)

        let failed = PreviewHarness()
