    @Test func deadlineClosesSocketAndStopsAudioEvenWhileDraining() async throws {
        let gate = PreviewDeadlineGate()
        let harness = PreviewHarness(waitForDeadline: { await gate.wait() })
        defer { harness.close() }
        let session = try await harness.startReady()
        session.emit(.audio(Data([1, 2]), itemID: nil))
        session.emit(.turnComplete)
        try await waitUntil { session.closed }
        #expect(harness.preview.isRunning)
        await gate.expire()
        try await waitUntil { !harness.preview.isRunning }
        #expect(harness.audio.stopCount == 1)
        #expect(harness.preview.errorMessage != nil)
    }

    @Test func deadlineIncludesCredentialLookupAndSetupTime() async throws {
        let deadline = PreviewDeadlineGate()
        let credentials = PreviewCredentialGate()
        let harness = PreviewHarness(
            credential: { _ in await credentials.read() },
            waitForDeadline: { await deadline.wait() }
        )
        defer { harness.close() }
        harness.preview.start(appLanguageCode: "en", sample: "Fixed sample")
        try await waitUntil { credentials.waiting != nil }
        await deadline.expire()
        try await waitUntil { !harness.preview.isRunning }
        credentials.complete()
        await flushEvents()
        #expect(harness.sessions.isEmpty)
        #expect(harness.audio.starts.isEmpty)

        let setupDeadline = PreviewDeadlineGate()
        let setup = PreviewHarness(waitForDeadline: { await setupDeadline.wait() })
        defer { setup.close() }
        setup.preview.start(appLanguageCode: "en", sample: "Fixed sample")
        try await waitUntil { setup.sessions.count == 1 }
        await setupDeadline.expire()
        try await waitUntil { !setup.preview.isRunning }
        #expect(setup.sessions[0].closed)
        #expect(setup.audio.starts.isEmpty)
    }

    @Test func backgroundAndAudioInterruptionReleasePreviewResources() async throws {
        let harness = PreviewHarness()
        defer { harness.close() }
        let session = try await harness.startReady()
        harness.notifications.post(name: UIApplication.didEnterBackgroundNotification, object: nil)
        #expect(session.closed)
