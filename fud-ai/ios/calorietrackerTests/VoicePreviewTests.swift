        failed.audio.failStart = true
        failed.preview.start(appLanguageCode: "en", sample: "Fixed sample")
        try await waitUntil { failed.sessions.count == 1 }
        let session = failed.sessions[0]
        session.emit(.ready)
        try await waitUntil { !failed.preview.isRunning }
        #expect(session.closed)
        #expect(session.samples.isEmpty)
        #expect(failed.audio.stopCount == 1)
        #expect(failed.preview.errorMessage != nil)
    }

    @Test(arguments: [
        LiveEvent.error("Authorization: private-secret", code: "private-secret"),
        .hostedError(code: "private-secret", detail: "private-secret"),
        .closed(.failed("private-secret")),
        .toolCalls([LiveToolCall(id: "c", name: "log_water", argumentsJSON: "{}")]),
